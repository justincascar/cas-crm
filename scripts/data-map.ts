/**
 * Writes docs/DATA-MAP.md from the actual schema and src/lib/data-map.ts (J15).
 *
 * From CAS-CRM:
 *   npm run data-map
 */
import fs from "node:fs";
import path from "node:path";
import { DatabaseSync } from "node:sqlite";
import { DATA_MAP, STORAGE_WORDS } from "../src/lib/data-map.ts";
import { migrate } from "../src/lib/db/migrate.ts";

export function schemaColumns(): Map<string, string[]> {
  const db = new DatabaseSync(":memory:");
  db.exec(fs.readFileSync(path.join(process.cwd(), "src/lib/db/schema.sql"), "utf8"));
  migrate(db);
  const out = new Map<string, string[]>();
  for (const table of db.prepare(`SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name`).all() as Array<{ name: string }>) {
    out.set(table.name, (db.prepare(`PRAGMA table_info(${table.name})`).all() as Array<{ name: string }>).map((column) => column.name));
  }
  db.close();
  return out;
}

export function renderDataMap(): string {
  const schema = schemaColumns();
  const lines = [
    "# Data map",
    "",
    "Generated by `npm run data-map` from the database schema and `src/lib/data-map.ts`. Do not edit by hand. It feeds the DPIA.",
    "",
    `**Where it is stored.** ${STORAGE_WORDS}`,
    "",
    "**Special kinds of data.** Licence points and endorsement codes, and \"No points\", are **criminal offence data**. Bank statements and the client's means are **financial data**. Signatures are kept as evidence of signing.",
    "",
    "Retention periods marked \"awaiting adviser\" are defaults in Settings → Retention and deletion until CAS's adviser confirms them.",
    "",
    "| Table | Fields | About | Why it is held | Who can see it | How long it is kept | Kind |",
    "|---|---|---|---|---|---|---|",
  ];
  for (const entry of DATA_MAP) {
    const present = entry.columns.filter((column) => schema.get(entry.table)?.includes(column));
    if (!present.length) continue;
    lines.push(
      `| ${entry.table} | ${present.join(", ")} | ${entry.about.join(", ")} | ${entry.why} | ${entry.roles} | ${entry.retention} | ${entry.category ? `**${entry.category}**` : ""} |`,
    );
  }
  lines.push("");
  return lines.join("\n");
}

if (process.argv[1]?.endsWith("data-map.ts")) {
  fs.writeFileSync(path.join(process.cwd(), "docs", "DATA-MAP.md"), renderDataMap());
  console.log("docs/DATA-MAP.md written.");
}
